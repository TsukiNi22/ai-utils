##### Functions #####

def load(path: str) -> dict:
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError) as err:
        sys.exit(f"Error: cannot read {path}: {err}")

def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")

def gpu_text(inv: dict) -> str:
    gpus = inv["hardware"]["gpus"]
    return ", ".join(f"{g['name']} {g['vram_mb'] // 1024} GB" if g["vram_mb"] else g["name"] for g in gpus) or "no GPU"

def machine(inv: dict) -> str:
    hw = inv["hardware"]
    return f"{inv['os']}, {gpu_text(inv)}, {hw['ram_gb']} GB RAM, {hw['cpus']} CPUs"

class Studio:
    """The catalog, the inventory and the choices, and what each domain gets"""

    def __init__(self, catalog: dict, inv: dict, choices: dict) -> None:
        self.catalog, self.inv, self.choices = catalog, inv, choices
        self.tools = {t["id"]: t for t in catalog["tools"]}
        for extra in choices.get("extra", []): # found online / installed, not in the catalog
            self.tools[extra["id"]] = {"kind": "cli", "domains": {}, "detect": {}, **extra}
        self.commercial = choices.get("commercial", "ask")
        self.skip = set(choices.get("skip", []))
        self.servers = {}
        mapping = choices.get("mcp", {})
        for server in inv.get("mcp", []):
            target = mapping.get(server["name"], server.get("tool", ""))
            if target:
                self.servers.setdefault(target, []).append(server)

    def where(self, tid: str) -> list:
        tool = self.tools[tid]
        if "where" in tool:
            return tool["where"]
        return self.inv["tools"].get(tid, {}).get("where", [])

    def available(self, tid: str) -> bool:
        tool = self.tools[tid]
        if tid in self.skip:
            return False
        return bool(self.where(tid) or self.servers.get(tid) or tool["kind"] in ("web", "assets"))

    def allowed(self, tid: str) -> bool:
        return not (self.commercial == "yes" and self.tools[tid].get("commercial") == "no")

    def rank(self, tid: str, domain: str, role: str) -> tuple:
        tool = self.tools[tid]
        preferred = self.choices.get("prefer", {}).get(f"{domain}.{role}") == tid
        safe = 0 if self.commercial == "no" else {"yes": 0, "conditions": 1}.get(tool.get("commercial"), 2)
        return (not preferred, 0 if self.servers.get(tid) else RANK.get(tool["kind"], 6), safe)

    def candidates(self, domain: str, role: str) -> list:
        ids = [i for i, t in self.tools.items() if role in t["domains"].get(domain, []) and self.available(i) and self.allowed(i)]
        return sorted(ids, key=lambda i: self.rank(i, domain, role))

    def missing(self, domain: str) -> list:
        """Roles with no usable free tool (a connector spending credits does not count)"""
        roles = self.catalog["domains"][domain]["roles"]
        return [r for r in roles if not [i for i in self.candidates(domain, r) if self.tools[i]["kind"] != "connector"]]

    def label(self, tid: str) -> str:
        servers = self.servers.get(tid, [])
        name = self.tools[tid]["name"]
        return f"{name} (MCP `{servers[0]['name']}`)" if servers else name

    ##### Sections #####

    def roles_table(self, domain: str) -> str:
        rows = ["| Task | Use | Also here | Why |", "|---|---|---|---|"]
        for role, about in self.catalog["domains"][domain]["roles"].items():
            ids = self.candidates(domain, role)
            if not ids:
                rows.append(f"| {cell(about)} | - (see *Missing*) | - | - |")
                continue
            best = self.tools[ids[0]]
            credits = " - spends credits" if best.get("cost") == "credits" else ""
            also = ", ".join(self.tools[i]["name"] for i in ids[1:4]) or "-"
            rows.append(f"| {cell(about)} | **{cell(self.label(ids[0]))}**{credits} | {cell(also)} | {cell(best.get('why', ''))} |")
        return "\n".join(rows)

    def place(self, entry: str) -> str:
        kind, _, value = entry.partition(":")
        return {"bin": f"`{value}`", "flatpak": f"flatpak `{value}` (`flatpak run {value}`)",
                "python": f"Python module `{value}`", "dir": f"folder `{value}`", "appimage": f"AppImage `{value}`",
                "connector": f"claude.ai connector (tools `mcp__claude_ai_{value}__*`)"}.get(kind, "declared by the user (not scanned)")

    def drive(self, tid: str) -> str:
        tool = self.tools[tid]
        how = self.choices.get("howto", {}).get(tid)
        if how:
            return how
        if self.servers.get(tid):
            fallback = "the commands below" if tool.get("recipes") else "the app opened for the user with the exact steps"
            return f"its MCP server first; {fallback} when the server is not running"
        if tool["kind"] in ("cli", "python"):
            return "command line, headless (the commands below)"
        if tool["kind"] == "connector":
            return "its tools directly in the conversation" + (", after saying it spends credits" if tool.get("cost") == "credits" else "")
        if tool["kind"] in ("web", "assets"):
            return "in the browser: give the link and the steps, or download what the user picks"
        if tool.get("recipes"):
            return "GUI for interactive work; headless through the commands below"
        return "GUI: prepare the files, then open it for the user with the exact steps"

    def tool_block(self, tid: str) -> str:
        tool = self.tools[tid]
        lines = [f"### {tool['name']}", f"- **What**: {KINDS.get(tool['kind'], tool['kind'])} - {tool.get('why', '')}"]
        places = [self.place(w) for w in self.where(tid)]
        if tool["kind"] in ("web", "assets"):
            places = [tool.get("install", {}).get("url", "")]
        if places:
            lines.append(f"- **Where**: {', '.join(p for p in places if p)}")
        for s in self.servers.get(tid, []):
            lines.append(f"- **MCP**: server `{s['name']}` ({s['scope']}, `{s['target']}`): `ToolSearch \"+{s['name']}\"` "
                         f"loads its tools `mcp__{s['name']}__*`")
        mcp = tool.get("mcp") or {}
        if not self.servers.get(tid) and mcp.get("command"):
            lines.append(f"- **MCP available, not configured**: `{mcp['command']}` - {mcp.get('note', '')}")
        lines.append(f"- **How**: {self.drive(tid)}")
        version = self.inv["tools"].get(tid, {}).get("version")
        if version:
            lines.append(f"- **Version**: {version}")
        lic = f"- **License**: {tool.get('license', '?')} - commercial: **{tool.get('commercial', '?')}**"
        if tool.get("note"):
            lic += f" ({tool['note']})"
        if tool.get("cost", "free") != "free":
            lic += f" - cost: {tool['cost']}"
        lines.append(lic)
        if self.commercial == "yes" and tool.get("commercial") == "no":
            lines.append("- **Personal work only**: left out of the table (commercial use needed).")
        if tool.get("gpu"):
            lines.append(f"- **GPU**: {tool['gpu']}")
        recipes = tool.get("recipes", [])
        if recipes:
            lines.append("- **Commands**:")
            lines += [f"  - {what}: `{cmd}`" for what, cmd in recipes]
        return "\n".join(lines)

    def tools_section(self, domain: str) -> str:
        ids = [i for i, t in self.tools.items() if domain in t["domains"] and self.available(i)]
        ids.sort(key=lambda i: (RANK.get(self.tools[i]["kind"], 6) if not self.servers.get(i) else 0, self.tools[i]["name"]))
        blocks = [self.tool_block(i) for i in ids]
        for name, server in self.unmatched(domain):
            how = self.choices.get("howto", {}).get(name, "`ToolSearch \"+" + name + "\"` loads its tools, read their descriptions")
            blocks.append(f"### MCP server `{name}`\n- **Where**: {server['scope']}, `{server['target']}`\n- **How**: {how}")
        return "\n\n".join(blocks) or "Nothing installed for this domain yet: see *Missing*."

    def unmatched(self, domain: str) -> list:
        return [(s["name"], s) for s in self.servers.get(f"domain:{domain}", [])]

    def missing_section(self, domain: str) -> str:
        declined = set(self.choices.get("declined", []))
        lines = []
        for role in self.missing(domain):
            about = self.catalog["domains"][domain]["roles"][role]
            options = [i for i, t in self.tools.items() if role in t["domains"].get(domain, []) and not self.available(i)
                       and self.allowed(i) and t["kind"] != "connector" and i not in declined and i not in self.skip]
            text = "; ".join(self.offer(i) for i in options[:3]) or "nothing free in the catalog: search online with `/setup-studio`"
            refused = [self.tools[i]["name"] for i, t in self.tools.items() if i in declined and role in t["domains"].get(domain, [])]
            if refused:
                text += f" (declined: {', '.join(refused)})"
            lines.append(f"- **{about}**: {text}")
        return "\n".join(lines) or "Every task of this domain has a tool here."

    def offer(self, tid: str) -> str:
        tool = self.tools[tid]
        inst = tool.get("install", {})
        how = [f"dnf `{inst['dnf']}`" if "dnf" in inst else "", f"flatpak `{inst['flatpak']}`" if "flatpak" in inst else "",
               f"`uv tool install {inst['pip']}`" if "pip" in inst else "", inst.get("url", "") if len(inst) == 1 else ""]
        return f"{tool['name']} ({tool.get('license', '?')}, commercial {tool.get('commercial', '?')}; {' / '.join(h for h in how if h)})"

    def description(self, domain: str) -> str:
        names = [self.tools[i]["name"] for i, t in self.tools.items() if domain in t["domains"] and self.available(i)
                 and t["kind"] not in ("web", "assets")]
        title = self.catalog["domains"][domain]["title"]
        head = (f"{title} with the tools installed on this computer (generated by setup-studio): which one to use for each "
                f"task, where it is, how to drive it (MCP server, command line, GUI) and why, with ready commands and "
                f"license / commercial-use notes. Use whenever the user wants to {TRIGGERS[domain]}.")
        tail = f" Here: {', '.join(names)}."
        while names and len(head + tail) > 1024:
            names.pop()
            tail = f" Here: {', '.join(names)}..."
        return (head + (tail if names else ""))[:1024].replace("<", "").replace(">", "")

    def domains_table(self, domains: list) -> str:
        rows = ["| Domain | Skill | For | Main tools here |", "|---|---|---|---|"]
        for d in domains:
            names = [self.tools[i]["name"] for i, t in self.tools.items() if d in t["domains"] and self.available(i)
                     and t["kind"] not in ("web", "assets")]
            rows.append(f"| {cell(self.catalog['domains'][d]['title'])} | `studio-{d}` | {cell(TRIGGERS[d])} | "
                        f"{cell(', '.join(names[:6]) or '-')} |")
        return "\n".join(rows)

    def machine_lines(self) -> str:
        inv = self.inv
        lines = [f"- {machine(inv)}, {inv['hardware']['disk_free_gb']} GB free.",
                 "- Installers: " + ", ".join(k for k, v in inv["installers"].items() if v) + "."]
        lines += [f"- MCP `{s['name']}` ({s['scope']}): {s['target']}" for s in inv.get("mcp", [])]
        if inv.get("connectors"):
            lines.append("- claude.ai connectors: " + ", ".join(inv["connectors"]) + ".")
        lines.append(f"- Commercial use: {COMMERCIAL[self.commercial]}")
        return "\n".join(lines)

##### Writing #####

def fill(template: str, values: dict) -> str:
    text = open(os.path.join(SKILL_DIR, "templates", template), encoding="utf-8").read()
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    left = re.findall(r"\{\{[A-Z_]+\}\}", text)
    if left:
        sys.exit(f"Error: {template}: placeholders left {left}")
    return text

def kept(folder: str) -> dict:
    """The notes of the files already there, by skill name"""
    notes = {}
    names = os.listdir(folder) if os.path.isdir(folder) else []
    for name in names:
        path = os.path.join(folder, name, "SKILL.md")
        if name.startswith("studio") and os.path.isfile(path):
            notes.update(dict(KEEP.findall(open(path, encoding="utf-8").read())))
    return notes

def guard(path: str, force: bool) -> None:
    if os.path.exists(path) and MARK not in open(path, encoding="utf-8").read() and not force:
        sys.exit(f"Error: {path} was not generated by setup-studio: move it away or pass --force")

def demote(text: str) -> str:
    """Body of a domain skill inside the combined one: no frontmatter, headings one level down"""
    body = re.sub(r"\A---\n.*?\n---\n+", "", text, flags=re.S)
    return re.sub(r"^(#+) ", lambda m: "#" + m.group(1) + " ", body, flags=re.M)

def build(st: Studio, domains: list, notes: dict, date: str) -> dict:
    """name -> SKILL.md text"""
    inv = st.inv
    out = {}
    for d in domains:
        name = f"studio-{d}"
        out[name] = fill("domain.md", {
            "NAME": name, "DESCRIPTION": st.description(d), "DATE": date, "TITLE": st.catalog["domains"][d]["title"],
            "HOST": inv["host"], "MACHINE": machine(inv), "COMMERCIAL": COMMERCIAL[st.commercial],
            "ROLES": st.roles_table(d), "TOOLS": st.tools_section(d), "MISSING": st.missing_section(d),
            "GPU": gpu_text(inv), "KEEP": notes.get(name, st.choices.get("notes", {}).get(d, "")),
        })
    desc = ("Studio router generated by setup-studio for this computer: reads a creative request (audio, image, video, "
            "3D, simulation / VFX / rendering) and loads the studio skill of each domain it touches, which says which "
            "installed tool to use, where, how and why. Use when the user invokes /studio.")
    out["studio"] = fill("router.md", {
        "DESCRIPTION": desc, "DATE": date, "HOST": inv["host"], "DOMAINS": st.domains_table(domains),
        "MACHINE": st.machine_lines(), "KEEP": notes.get("studio", ""),
    })
    return out

def single(skills: dict, domains: list) -> str:
    """One skill with the router and every domain (claude.ai)"""
    router = skills["studio"]
    router = router.replace("disable-model-invocation: true\n", "")
    router = re.sub(r"^description: .*$", "description: " + (
        "Creative work with the tools of the user's computer and the connected services (generated by setup-studio): "
        "audio, image, video, 3D, simulation / VFX / rendering - which tool to use for each task, where it is, how to "
        "drive it and why, with ready commands and license / commercial-use notes. Use whenever the user wants to make "
        "or edit sound, music, voice, images, videos, 3D models, simulations, effects or renders."), router, count=1, flags=re.M)
    router = router.replace("loads the studio skill of each\ndomain it touches", "reads the part of each domain it touches")
    note = ("\nOn claude.ai the programs below run on the user's computer, not here: give the user the commands and the "
            "steps; the claude.ai connectors (ElevenLabs, Canva...) are used directly.\n")
    router = router.replace("\n## Domains", note + "\n## Domains", 1)
    bodies = [demote(skills[f"studio-{d}"]).strip().replace("assets/icon.", f"assets/icons/{d}.") for d in domains]
    return router.rstrip() + "\n\n" + "\n\n".join(bodies) + "\n"

def write(folder: str, name: str, text: str, force: bool, dry: bool) -> str:
    path = os.path.join(folder, name, "SKILL.md")
    guard(path, force)
    if dry:
        print(f"would write {path} ({text.count(chr(10))} lines)")
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"written {path} ({text.count(chr(10))} lines)")
    return os.path.dirname(path)

def copy_assets(folder: str, domains: list, single_skill: bool, dry: bool) -> None:
    """The logo in the router (with every icon in the combined skill), the icon of its domain in each domain skill."""
    name = os.path.basename(folder)
    pairs = []
    if name == "studio":
        pairs += [(os.path.join(ASSETS, f), os.path.join(folder, "assets", f)) for f in LOGOS]
        if single_skill:
            pairs += [(os.path.join(ASSETS, "icons", f"{d}.{ext}"), os.path.join(folder, "assets", "icons", f"{d}.{ext}"))
                      for d in domains for ext in ("svg", "png")]
    else:
        d = name[len("studio-"):]
        pairs += [(os.path.join(ASSETS, "icons", f"{d}.{ext}"), os.path.join(folder, "assets", f"icon.{ext}")) for ext in ("svg", "png")]
    for src, dest in pairs:
        if not os.path.isfile(src):
            print(f"warning: {src} missing, not copied")
            continue
        if not dry:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copyfile(src, dest)
    print(f"{'would copy' if dry else 'copied'} {len(pairs)} asset(s) into {name}/assets")

def zip_skill(folder: str, dest: str) -> None:
    os.makedirs(dest, exist_ok=True)
    name = os.path.basename(folder)
    target = os.path.join(dest, name + ".zip")
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
        for root, dirs, files in os.walk(folder):
            dirs[:] = [d for d in dirs if d != "reference"] # state.json: this computer only, never uploaded
            for f in files:
                full = os.path.join(root, f)
                z.write(full, os.path.join(name, os.path.relpath(full, folder)))
    print(f"zip {target}")

def main() -> int:
    ap = argparse.ArgumentParser(description="Generate the studio skills of this computer")
    ap.add_argument("--inventory", required=True)
    ap.add_argument("--choices", required=True)
    ap.add_argument("--out", default=os.path.join(os.path.expanduser("~"), ".claude", "skills"))
    ap.add_argument("--single", action="store_true")
    ap.add_argument("--zip")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--catalog", default=CATALOG)
    a = ap.parse_args()
    catalog, inv, choices = load(a.catalog), load(a.inventory), load(a.choices)
    domains = choices.get("domains", list(catalog["domains"]))
    bad = [d for d in domains if d not in catalog["domains"]]
    if bad or choices.get("commercial", "ask") not in COMMERCIAL:
        sys.exit(f"Error: unknown domain {bad} or commercial not in {list(COMMERCIAL)}")
    st = Studio(catalog, inv, choices)
    skills = build(st, domains, kept(a.out), inv["date"])
    written = []
    if a.single:
        written.append(write(a.out, "studio", single(skills, domains), a.force, a.dry_run))
    else:
        for name in ["studio"] + [f"studio-{d}" for d in domains]:
            written.append(write(a.out, name, skills[name], a.force, a.dry_run))
        for d in catalog["domains"]: # a domain dropped since the last run
            old = os.path.join(a.out, f"studio-{d}", "SKILL.md")
            if d not in domains and os.path.exists(old) and MARK in open(old, encoding="utf-8").read():
                print(f"{'would remove' if a.dry_run else 'removed'} {os.path.dirname(old)} (domain dropped)")
                if not a.dry_run:
                    shutil.rmtree(os.path.dirname(old))
    for folder in written:
        copy_assets(folder, domains, a.single, a.dry_run)
    if a.dry_run:
        return 0
    state = os.path.join(written[0], "reference", "state.json")
    os.makedirs(os.path.dirname(state), exist_ok=True)
    with open(state, "w", encoding="utf-8") as f:
        json.dump({"generated": inv["date"], "inventory": inv, "choices": choices}, f, indent=2)
    print(f"written {state}")
    if a.zip:
        for folder in written:
            zip_skill(folder, a.zip)
    return 0

if __name__ == "__main__":
    sys.exit(main())
